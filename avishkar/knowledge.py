def cwe_refs(ids) -> list[dict]:
    return [{"id": f"CWE-{i}", "name": CWE_NAMES.get(i, "See MITRE"), "url": f"https://cwe.mitre.org/data/definitions/{i}.html"}
            for i in (ids or [])]


def describe(rule_id: str, category: str | None = None) -> dict:
    """Knowledge for a rule id. Unknown / external rules (Semgrep 'SG:*', Gitleaks 'GL:*') fall back to a category default
    and say plainly that no curated entry exists."""
    k = RULES.get(rule_id)
    if k:
        return {"ruleId": rule_id, "curated": True, "kbVersion": KB_VERSION, **{x: k[x] for x in
                ("name", "category", "detection", "why", "impact", "remediation", "secureExample", "owasp")},
                "cwe": cwe_refs(k["cwe"])}
    g = GENERIC.get(category or "", {})
    return {"ruleId": rule_id, "curated": False, "kbVersion": KB_VERSION, "name": rule_id, "category": category,
            "detection": {"method": "external" if rule_id.startswith(("SG:", "GL:")) else "unknown", "assurance": "heuristic"},
            "why": g.get("why", "No curated explanation exists for this rule yet; see the rule's own documentation."),
            "impact": g.get("impact", "Unknown."), "remediation": g.get("remediation", "See the scanner output and rule docs."),
            "secureExample": None, "owasp": None, "cwe": cwe_refs(g.get("cwe"))}


def rule_ids() -> list[str]:
    return sorted(RULES)
