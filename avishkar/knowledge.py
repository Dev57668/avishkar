"""Static, reviewable knowledge base for every detection rule: CWE mapping, explanation, impact, remediation and a
secure example. It is *reference text*, authored once and versioned in git; it never changes a finding's severity,
confidence or score, and nothing here is generated by a model.

`detection.method`: ast | tokens | regex | manifest | external
`detection.assurance`:
  structural - the dangerous construct was matched in a parsed syntax tree / token stream (it is present in the code;
               whether it is *exploitable* depends on data flow the scanner does not prove)
  heuristic  - a naming/shape heuristic: expect false positives; treat as a lead to verify
  database   - matched against a bundled advisory list (versions are facts, relevance to your code is not proven)
CWE ids are the closest reasonable classification, not a certification.
"""
